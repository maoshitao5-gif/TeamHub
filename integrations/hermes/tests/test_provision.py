"""Provisioning accepts only the checksum-pinned, regular-file source archive."""
import hashlib
import importlib.util
import io
from pathlib import Path
import tarfile

import pytest


def provision():
    path = Path(__file__).resolve().parents[3] / 'scripts/prepare-hermes.py'
    spec = importlib.util.spec_from_file_location('prepare_hermes', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def archive(tmp_path, name='pinned/run_agent.py', *, link=False):
    path = tmp_path / 'archive.tgz'
    with tarfile.open(path, 'w:gz') as tar:
        info = tarfile.TarInfo(name)
        data = b'print("hermes")\n'
        if link:
            info.type = tarfile.SYMTYPE
            info.linkname = '/etc/passwd'
            tar.addfile(info)
        else:
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return path, {'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'source_prefix': 'pinned'}


def test_extracts_only_verified_source_and_can_verify_existing_tree(tmp_path):
    module = provision()
    path, manifest = archive(tmp_path)
    target = tmp_path / 'source'
    module.prepare_source(path, target, manifest)
    assert (target / 'run_agent.py').read_text() == 'print("hermes")\n'
    module.prepare_source(path, target, manifest)
    (target / 'run_agent.py').write_text('modified')
    with pytest.raises(ValueError):
        module.prepare_source(path, target, manifest)


@pytest.mark.parametrize('name,link', [('pinned/../../outside.py', False),
    ('/outside.py', False), ('other/run_agent.py', False), ('pinned/linked', True)])
def test_rejects_path_traversal_other_release_and_symlinks(tmp_path, name, link):
    module = provision()
    path, manifest = archive(tmp_path, name, link=link)
    with pytest.raises(ValueError):
        module.prepare_source(path, tmp_path / 'source', manifest)
    assert not (tmp_path / 'outside.py').exists()


def test_rejects_wrong_archive_checksum_before_creating_destination(tmp_path):
    module = provision()
    path, manifest = archive(tmp_path)
    manifest['sha256'] = '0' * 64
    with pytest.raises(ValueError):
        module.prepare_source(path, tmp_path / 'source', manifest)
    assert not (tmp_path / 'source').exists()


@pytest.mark.parametrize('extra', ['extra.py', '.env', 'tools/hidden.py'])
def test_existing_source_rejects_extra_files_not_present_in_pinned_archive(tmp_path, extra):
    module = provision()
    path, manifest = archive(tmp_path)
    target = tmp_path / 'source'
    module.prepare_source(path, target, manifest)
    unexpected = target / extra
    unexpected.parent.mkdir(parents=True, exist_ok=True)
    unexpected.write_text('unverified content')
    with pytest.raises(ValueError, match='unexpected'):
        module.prepare_source(path, target, manifest)


def test_generated_bytecode_does_not_prevent_source_verification(tmp_path):
    module = provision()
    path, manifest = archive(tmp_path)
    target = tmp_path / 'source'
    module.prepare_source(path, target, manifest)
    cache = target / '__pycache__'
    cache.mkdir()
    (cache / 'run_agent.cpython-314.pyc').write_bytes(b'generated bytecode')
    module.prepare_source(path, target, manifest)
